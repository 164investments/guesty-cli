//! Precomputes the operation catalog from the bundled API documents and
//! writes it to `$OUT_DIR/catalog_index.rs` as Rust statics: every
//! operation's fields, its byte range in its OpenAPI document, its search
//! words, and each document's top-level members. At runtime nothing is
//! scanned; describe parses only the operation it shows.

use std::fmt::Write;
use std::path::Path;

#[allow(dead_code, unused_imports)]
#[path = "../src/json.rs"]
mod json;

#[allow(dead_code)]
#[path = "../src/mcp/js.rs"]
mod js;

#[allow(dead_code)]
#[path = "../src/mcp/words.rs"]
mod words;

#[allow(dead_code)]
mod scan;

mod index;

/// The documents, from the repository root (the CLI package).
pub const DOCUMENTS: [&str; 4] =
    ["api-spec.json", "openapi-spec.json", "booking-engine-api-spec.json", "booking-engine-openapi-spec.json"];

fn literal(value: &str) -> String {
    // A str's Debug form is a valid Rust string literal.
    format!("{value:?}")
}

fn option(value: Option<&str>) -> String {
    match value {
        Some(v) => format!("Some({})", literal(v)),
        None => "None".into(),
    }
}

/// Words as their places in the sorted vocabulary.
fn words(list: &[String], vocabulary: &[String]) -> String {
    let items: Vec<String> =
        list.iter().map(|w| vocabulary.binary_search(w).expect("in the vocabulary").to_string()).collect();
    format!("&[{}]", items.join(", "))
}

fn span(span: Option<scan::Span>) -> String {
    match span {
        Some(s) => format!("Some(Span {{ start: {}, end: {} }})", s.start, s.end),
        None => "None".into(),
    }
}

fn render(index: &index::Index) -> String {
    let mut out = String::new();
    let n = index.operations.len();
    out.push_str("// Generated by crates/guesty-core/build/main.rs. Do not edit.\n");
    assert!(index.vocabulary.len() <= usize::from(u16::MAX));
    let _ = writeln!(out, "static WORDS: [&str; {}] = [", index.vocabulary.len());
    for word in &index.vocabulary {
        let _ = writeln!(out, "    {},", literal(word));
    }
    out.push_str("];\n");
    for (d, doc) in index.docs.iter().enumerate() {
        let _ = writeln!(out, "static DOC_{d}_TOP: [(&str, Span); {}] = [", doc.top.len());
        for (key, span) in &doc.top {
            let _ = writeln!(out, "    ({}, Span {{ start: {}, end: {} }}),", literal(key), span.start, span.end);
        }
        out.push_str("];\n");
        let _ = writeln!(
            out,
            "static DOC_{d}_VALUES: [OnceLock<Json>; {}] = [const {{ OnceLock::new() }}; {}];",
            doc.top.len(),
            doc.top.len()
        );
    }
    let _ = writeln!(out, "static OPERATIONS: [Operation; {n}] = [");
    for op in &index.operations {
        let _ = writeln!(
            out,
            "    Operation {{ id: {}, api: Api::{}, group: {}, method: {}, path: {}, title: {}, operation_id: {}, docs_url: {}, deprecated: {}, changes_data: {}, doc: {}, span: {}, description_span: {}, spec: OnceLock::new(), description: OnceLock::new() }},",
            literal(&op.id),
            op.api,
            literal(&op.group),
            literal(&op.method),
            literal(&op.path),
            literal(&op.title),
            option(op.operation_id.as_deref()),
            literal(&op.docs_url),
            op.deprecated,
            op.changes_data,
            op.doc,
            span(op.span),
            span(op.description_span),
        );
    }
    out.push_str("];\n");
    let _ = writeln!(out, "static SEARCH: [Indexed; {n}] = [");
    for entry in &index.search {
        let fields: Vec<String> = entry.fields.iter().map(|f| words(f, &index.vocabulary)).collect();
        let title = words(&entry.title_words, &index.vocabulary);
        let _ = writeln!(out, "    Indexed {{ fields: [{}], title_words: {title} }},", fields.join(", "));
    }
    out.push_str("];\n");
    out
}

fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let root = Path::new(&manifest).join("../..");
    let read = |name: &str| {
        let path = root.join(name);
        println!("cargo:rerun-if-changed={}", path.display());
        std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
    };
    let [open_api, open_api_document, booking, booking_document] = DOCUMENTS.map(read);
    for file in ["main.rs", "index.rs", "scan.rs", "../src/mcp/words.rs", "../src/mcp/js.rs", "../src/json.rs"] {
        println!("cargo:rerun-if-changed=build/{file}");
    }
    let index = index::build(&open_api, &open_api_document, &booking, &booking_document);
    let out = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("catalog_index.rs");
    std::fs::write(&out, render(&index)).unwrap_or_else(|e| panic!("{}: {e}", out.display()));
}
